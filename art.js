const artIcons = new Map();
function artIcon(id) {
  if (!artIcons.has(id)) {
    const tile=document.createElement('canvas');tile.width=tile.height=24;
    pixelAsset(tile.getContext('2d'),id,0,0,24);
    artIcons.set(id,tile.toDataURL());
  }
  return artIcons.get(id);
}
